function initialLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && STRINGS[saved]) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.language || 'it').slice(0, 2);
  return STRINGS[nav] ? nav : 'it';
}

let current = initialLang();

export function getLang() { return current; }
export function setLang(code) {
  if (!STRINGS[code]) return;
  current = code;
  try { localStorage.setItem('lang', code); } catch { /* ignore */ }
  document.documentElement.lang = code;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.it[key] ?? key;
  if (vars && typeof s === 'string') {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

const LOCALES = { it: 'it-IT', en: 'en-GB', ro: 'ro-RO', es: 'es-ES' };

/** Formatta {y,m,d} con mese e giorno facoltativi. */
export function formatDate(date) {
  if (!date || !date.y) return '';
  if (date.m && date.d) {
    return new Date(Date.UTC(date.y, date.m - 1, date.d))
      .toLocaleDateString(LOCALES[current], { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
  }
  if (date.m) return `${t('months')[date.m - 1]} ${date.y}`;
  return String(date.y);
}

export function formatDateTime(ms) {
  if (!ms) return '';
  return new Date(ms).toLocaleString(LOCALES[current], {
    day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
  });
}
